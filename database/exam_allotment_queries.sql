-- Exam Allotment Tables & Roles

-- 1. Create Tables
CREATE TABLE IF NOT EXISTS public.exam_rooms (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    block TEXT NOT NULL,
    floor INTEGER NOT NULL,
    room_number TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.exam_allotments (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    faculty_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    exam_type TEXT NOT NULL CHECK (exam_type IN ('Theory', 'Practical')),
    exam_date DATE NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    room_id UUID NOT NULL REFERENCES public.exam_rooms(id) ON DELETE CASCADE,
    allocated_by UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Indexes
CREATE INDEX IF NOT EXISTS idx_exam_allotments_faculty ON public.exam_allotments(faculty_id);
CREATE INDEX IF NOT EXISTS idx_exam_allotments_date ON public.exam_allotments(exam_date);
CREATE INDEX IF NOT EXISTS idx_exam_rooms_block ON public.exam_rooms(block);

-- 3. RLS Policies
ALTER TABLE public.exam_rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exam_allotments ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    CREATE POLICY "Anyone can view exam rooms" ON public.exam_rooms FOR SELECT USING (true);
    CREATE POLICY "Admins can manage exam rooms" ON public.exam_rooms FOR ALL USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'));
    
    CREATE POLICY "Anyone can view exam allotments" ON public.exam_allotments FOR SELECT USING (true);
    CREATE POLICY "Faculty and Admins can create allotments" ON public.exam_allotments FOR INSERT WITH CHECK (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role IN ('faculty', 'admin')));
    CREATE POLICY "Creators can update allotments" ON public.exam_allotments FOR UPDATE USING (auth.uid() = allocated_by);
    CREATE POLICY "Creators can delete allotments" ON public.exam_allotments FOR DELETE USING (auth.uid() = allocated_by);
EXCEPTION
    WHEN duplicate_object THEN null;
END $$;

